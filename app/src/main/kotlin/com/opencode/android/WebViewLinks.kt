package com.opencode.android

import java.io.File
import java.net.URI

/**
 * Where a link tapped in the OpenCode WebView belongs.
 *
 * The shell has exactly one page: the local OpenCode server. A link that leaves that origin would
 * replace the paired chat with a foreign page, so it is opened outside the WebView instead. A file
 * path the chat refers to is not a page at all: the app opens it in its own file manager and
 * viewers.
 *
 * The rules are pure so they can be tested without a WebView.
 */
object WebViewLinks {

    /** What the shell should do with a tapped link. */
    enum class Target {
        /** The URL is served by the OpenCode instance: load it in the WebView. */
        WEB_VIEW,

        /** Open it outside the WebView: a file path in the app's viewers, anything else elsewhere. */
        EXTERNAL,

        /** Never follow the link (`javascript:`, `content:`, `intent:`, malformed input). */
        IGNORE,
    }

    /** Schemes that are safe to hand to the system. `file` is handled separately. */
    private val EXTERNAL_SCHEMES = setOf("http", "https", "mailto", "tel", "sms")

    /** Hosts that name the loopback interface the server binds to. */
    private val LOOPBACK_HOSTS = setOf("127.0.0.1", "localhost", "::1")

    /** Decide what the WebView must do with [url] while it is paired with [baseUrl]. */
    fun classify(url: String?, baseUrl: String): Target {
        val value = url?.trim().orEmpty()
        if (value.isEmpty()) return Target.IGNORE
        val uri = parse(value)
        if (uri == null) {
            // java.net.URI is strict; a plain path with a space still names a local file.
            return if (isBarePath(value)) Target.EXTERNAL else Target.IGNORE
        }
        val scheme = uri.scheme?.lowercase()
        if (scheme == null) {
            // A bare absolute path is a file of the project, not a page of the server.
            return if (isBarePath(value) && uri.authority == null) Target.EXTERNAL else Target.IGNORE
        }
        if (scheme == "file") return Target.EXTERNAL
        if (scheme !in EXTERNAL_SCHEMES) return Target.IGNORE
        return if (isServerOrigin(uri, baseUrl)) Target.WEB_VIEW else Target.EXTERNAL
    }

    /** Local file a tapped link points at, or null when the link is not a local path. */
    fun localFile(url: String?): File? {
        val value = url?.trim().orEmpty()
        if (value.isEmpty()) return null
        val uri = parse(value)
        if (uri == null) return if (isBarePath(value)) File(value) else null
        val scheme = uri.scheme?.lowercase()
        val path = when {
            scheme == "file" -> uri.path
            // `getPath` drops a `#L10` fragment the chat adds to a selected line.
            scheme == null && isBarePath(value) && uri.authority == null -> uri.path ?: value
            else -> null
        }
        return path?.takeIf { it.isNotEmpty() }?.let { File(it) }
    }

    /**
     * True when [url] is content generated by the page itself (an HTML preview iframe), not a
     * navigation to another site.
     */
    fun isInlineContent(url: String?): Boolean {
        val value = url?.trim().orEmpty()
        if (value.isEmpty()) return false
        return when (parse(value)?.scheme?.lowercase()) {
            "about", "blob", "data" -> true
            else -> false
        }
    }

    /** True when [url] is served by the OpenCode instance the WebView is paired with. */
    private fun isServerOrigin(uri: URI, baseUrl: String): Boolean {
        val base = parse(baseUrl) ?: return false
        if (uri.scheme?.lowercase() != base.scheme?.lowercase()) return false
        val host = normalizeHost(uri.host) ?: return false
        val baseHost = normalizeHost(base.host) ?: return false
        if (host !in LOOPBACK_HOSTS || baseHost !in LOOPBACK_HOSTS) return false
        return portOf(uri) == portOf(base)
    }

    /** A single leading slash: `//host` is protocol-relative, not a file of this device. */
    private fun isBarePath(value: String): Boolean =
        value.startsWith("/") && !value.startsWith("//")

    private fun normalizeHost(host: String?): String? =
        host?.lowercase()?.removePrefix("[")?.removeSuffix("]")?.takeIf { it.isNotEmpty() }

    private fun portOf(uri: URI): Int = when {
        uri.port != -1 -> uri.port
        uri.scheme?.lowercase() == "https" -> 443
        else -> 80
    }

    private fun parse(value: String): URI? = try {
        URI(value)
    } catch (e: Exception) {
        null
    }
}
